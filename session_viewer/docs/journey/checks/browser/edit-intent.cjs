const assert = require('node:assert/strict');
module.exports = async (page, helpers) => {
    const {command, drawing} = helpers;
    await require('./replace.cjs')(page, helpers);
    await command(page, 'Orbit Right'); await command(page, 'Orbit Up');
    await command(page, 'Move 1.92,0,0.93');
    await command(page, 'Move 0.25,0,-0.15'); await command(page, 'Fit');
    const loaded = await drawing(page);
    await command(page, 'Unload Sources');
    let residency = JSON.parse(await page.locator('canvas').getAttribute('data-source-residency'));
    assert(residency.every(row => !row[1]));
    assert.equal(await drawing(page), loaded, 'Capturing prerequisites keep the display unchanged');
    const ui = JSON.parse(await page.locator('canvas').getAttribute('data-command-ui'));
    const field = ui.controls.find(control => control.key === 'command/input');
    const box = await page.locator('canvas').boundingBox(), rect = field.rect;
    await page.mouse.click(box.x + (rect[0] + rect[2]) / 2, box.y + (rect[1] + rect[3]) / 2);
    const before = ui.history.length;
    await page.keyboard.press('ControlOrMeta+A');
    await page.keyboard.type('Reload Sources'); await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.getElementById('status')?.textContent === 'Editable sources restored; display retained.');
    const result = JSON.parse(await page.locator('canvas').getAttribute('data-command-ui'));
    assert.equal(result.command, '');
    assert.equal(result.history.length, before + 2, 'One submission and one asynchronous result');
    assert(result.history.at(-2).endsWith('Reloading editable sources…'));
    assert(result.history.at(-1).endsWith('Editable sources restored; display retained.'));
    assert.equal(await drawing(page), loaded);
    const usage = JSON.parse(await page.locator('canvas').getAttribute('data-cpu-usage'));
    assert.equal(usage[2], 1, 'One restored Session shared across history');
    residency = JSON.parse(await page.locator('canvas').getAttribute('data-source-residency'));
    assert(residency.every(row => row[1]), 'Explicit reload still restores editable sources');
};
