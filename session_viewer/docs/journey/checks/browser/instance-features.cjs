const assert = require('node:assert/strict');
const fs = require('node:fs');
module.exports = async (page, helpers) => {
    await require('./projected-fit.cjs')(page, helpers);
    const value = name => page.locator('canvas').getAttribute(name).then(JSON.parse);
    const control = async key => {
        await page.waitForFunction(key => JSON.parse(document.querySelector('canvas').getAttribute('data-command-ui')).controls.some(c => c.key === key), key);
        const item = (await value('data-command-ui')).controls.find(c => c.key === key);
        await page.mouse.move((item.rect[0] + item.rect[2]) / 2, (item.rect[1] + item.rect[3]) / 2);
        await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
        await page.mouse.down(); await page.mouse.up();
    };
    const open = async file => {
        const choosing = page.waitForEvent('filechooser');
        await helpers.command(page, 'Open');
        await (await choosing).setFiles(file);
        await page.waitForFunction(() => document.querySelector('canvas').getAttribute('data-object-count') === '2');
    };
    for (const line of ['Close', 'Element Attributes Off', 'Element Interactions On']) await helpers.command(page, line);
    await open({name: 'instance-features.pb', mimeType: 'application/octet-stream', buffer: fs.readFileSync('assets/pb/course-instance-features.pb')});
    await helpers.command(page, 'Layers All'); await helpers.command(page, 'Fit');
    assert.deepEqual((await value('data-path-cpu')).slice(0, 3), [4, 4, 4]);
    const placements = await value('data-row-placements');
    const interactions = await helpers.drawing(page);
    await helpers.command(page, 'Element Attributes On');
    assert.notEqual(await helpers.drawing(page), interactions, 'Definition attributes appear at both placements');
    assert.deepEqual(await value('data-row-placements'), placements);
    let rows = await value('data-tree');
    const first = rows.find(row => row.label === 'First'), second = rows.find(row => row.label === 'Second');
    assert(first && second); assert.equal(rows.filter(row => row.label.startsWith('piece ')).length, 4);
    const firstPiece = rows.slice(rows.indexOf(first) + 1, first.end).find(row => row.label.startsWith('piece '));
    const secondPiece = rows.slice(rows.indexOf(second) + 1, second.end).find(row => row.label.startsWith('piece '));
    assert(firstPiece && secondPiece);
    const ui = await value('data-command-ui');
    assert(ui.controls.some(item => item.key === `tree/select/${firstPiece.key}`));
    await helpers.command(page, 'Select None');
    await control(`tree/select/${secondPiece.key}`);
    assert.deepEqual(await value('data-selected-ids'), [], 'A locked original instance cannot be selected through its features');
    await control(`tree/select/${firstPiece.key}`);
    await page.waitForFunction(id => JSON.parse(document.querySelector('canvas').getAttribute('data-selected-ids')).join() === String(id), first.ids[0]);
    assert(Number(await page.locator('canvas').getAttribute('data-highlight-bytes')) > 0);
    await helpers.command(page, 'Delete');
    assert.equal(await value('data-object-count'), 1); assert.equal((await value('data-tree')).filter(row => row.label.startsWith('piece ')).length, 2);
    await helpers.command(page, 'Undo');
    assert.equal(await value('data-object-count'), 2); assert.equal((await value('data-tree')).filter(row => row.label.startsWith('piece ')).length, 4);
    const downloading = page.waitForEvent('download'); await helpers.command(page, 'Save');
    const saved = await (await downloading).path();
    await helpers.command(page, 'Close'); await open(saved);
    await page.waitForFunction(() => document.querySelector('#status').textContent === 'Document replaced. Undo restores the previous document.');
    await helpers.command(page, 'Layers All'); await helpers.command(page, 'Fit');
    rows = await value('data-tree'); assert.equal(rows.filter(row => row.label.startsWith('piece ')).length, 4);
    assert.deepEqual((await value('data-path-cpu')).slice(0, 3), [4, 4, 4]);
    console.log(`${helpers.step.id}: actual instance feature display, toggles, locking, original selection and archive regeneration passed`);
};
