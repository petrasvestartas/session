"""Expand lesson directives into exact code steps taken from the verified patch series.

A lesson is maintained Markdown. Its code never lives in the Markdown: a directive names a
step and a file, and this module renders the change as CURRENT / REPLACE WITH, ADD BELOW or
NEW FILE blocks cut from the patch that the checkpoint verification already proved. The audit
replays every lesson literally, the way a reader types it, and requires the result to hash to
the recorded checkpoint.

Directives (HTML comments, one per line):

    <!-- file: NN path [type|copy] [hunks=1-3] [lines=A-B] [whole] -->
    <!-- listing: NN path -->          complete file at step NN, READ ONLY
    <!-- supplied: NN -->              tooling files copied, never typed
    <!-- tree: NN prefix -->           file tree at step NN, new/changed marked
    <!-- check: NN -->                 a cargo check point measured by compile_points.py
    <!-- checkpoint: NN -->            the end-of-lesson build/run commands
"""
from pathlib import Path
import argparse
import hashlib
import importlib.util
import json
import os
